def clip_text(s: str, n: int) -> str:
    return s if len(s) <= n else s[: n - 1].rstrip(" ;,") + "…"


def short(gid) -> str:
    """Короткая метка для схемы: 1000000XXXXXXXX100 → XXXXXXXX (уникальна в датасете)."""
    s = str(gid)
    return s[7:-3] if len(s) == 18 and s.startswith("1000000") else s
