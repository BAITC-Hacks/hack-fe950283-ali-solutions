"""Человекочитаемые числа для evidence и карточек."""


def kzt(x: float) -> str:
    x = float(x)
    if x >= 1e6:
        return f"{x / 1e6:.1f} млн ₸".replace(".0 ", " ")
    if x >= 1e3:
        return f"{x / 1e3:.0f} тыс ₸"
    return f"{x:.0f} ₸"


def pct(x: float) -> str:
    return f"{100 * float(x):.0f}%"


def word(n, forms) -> str:
    """Форма слова для числа; forms — для 1, 2–4 и 5+: («узел», «узла», «узлов»)."""
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return forms[2]
    return forms[0] if n % 10 == 1 else forms[1] if 2 <= n % 10 <= 4 else forms[2]


def plural(n, forms) -> str:
    """«1 узел», «3 узла», «11 узлов»."""
    return f"{n} {word(n, forms)}"


